tasks.register("checkBraces") {
    doLast {
        val file = file("src/main/java/com/example/ui/AlterAppScreen.kt")
        val lines = file.readLines()
        var openCount = 0
        var closeCount = 0
        val stack = mutableListOf<Int>()
        for ((index, line) in lines.withIndex()) {
            for (char in line) {
                if (char == '{') {
                    openCount++
                    stack.add(index + 1)
                } else if (char == '}') {
                    closeCount++
                    if (stack.isNotEmpty()) stack.removeLast()
                }
            }
        }
        println("Open: " + openCount)
        println("Close: " + closeCount)
        println("Unclosed braces from lines: " + stack.takeLast(10))
    }
}

